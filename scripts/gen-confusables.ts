/**
 * v3 F12 follow-up (ADR 0081 amendment 1): generates the confusables table from Unicode's own data (UTS #39,
 * `confusables.txt`, vendored unchanged at spec/unicode/confusables.txt), so that look-alike values are judged by
 * Unicode's list, never by a hand-made one.
 *
 *   npm run gen:confusables            write src/text/confusables.generated.ts
 *   npm run gen:confusables -- --check exit 1 if the committed file is stale
 *
 * To update: replace spec/unicode/confusables.txt with a newer release from
 * https://www.unicode.org/Public/security/latest/confusables.txt and run the generator.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const CONFUSABLES_SOURCE = resolve(root, 'spec/unicode/confusables.txt');
export const CONFUSABLES_OUT = resolve(root, 'src/text/confusables.generated.ts');

/** The generated module's text, from the source file's text. */
export function generateConfusables(source: string): string {
  const version = /^#\s*Version:\s*(\S+)/m.exec(source)?.[1] ?? 'unknown';
  const date = /^#\s*Date:\s*(.+)$/m.exec(source)?.[1]?.trim() ?? 'unknown';
  const rows: string[] = [];
  for (const line of source.split('\n')) {
    const data = line.split('#')[0]!.trim();
    if (data === '') continue;
    const [src, target] = data.split(';').map((x) => x.trim());
    if (!src || target === undefined || !/^[0-9A-F]+$/.test(src) || !/^[0-9A-F ]+$/.test(target))
      throw new Error(`confusables.txt: a line not understood: ${line}`);
    rows.push(`${src}:${target}`);
  }
  if (rows.length < 1000) throw new Error(`confusables.txt: only ${rows.length} mappings`);
  return [
    '// GENERATED by scripts/gen-confusables.ts from spec/unicode/confusables.txt (Unicode UTS #39). Do not edit.',
    `export const CONFUSABLES_VERSION = ${JSON.stringify(version)};`,
    `export const CONFUSABLES_DATE = ${JSON.stringify(date)};`,
    '/** Each mapping as `SOURCE:TARGET` in hex code points (TARGET space-separated), joined by `|`. */',
    `export const CONFUSABLES_DATA =\n  ${JSON.stringify(rows.join('|'))};`,
    '',
  ].join('\n');
}

function main(): void {
  const out = generateConfusables(readFileSync(CONFUSABLES_SOURCE, 'utf8'));
  if (process.argv.includes('--check')) {
    const now = readFileSync(CONFUSABLES_OUT, 'utf8');
    if (now !== out) {
      console.error('src/text/confusables.generated.ts is stale: run npm run gen:confusables');
      process.exit(1);
    }
    console.log('Generated confusables table is up to date.');
    return;
  }
  writeFileSync(CONFUSABLES_OUT, out);
  console.log(`Wrote ${CONFUSABLES_OUT}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
